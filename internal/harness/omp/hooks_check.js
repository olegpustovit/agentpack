import assert from "node:assert/strict";
import bridge from "./hooks.js";
const handlers = new Map();
bridge({on(name, handler) {handlers.set(name, handler);}});
const ctx = {cwd: "/workspace", sessionManager: {getSessionId() {return "session";}}};
let response = {}, status = 0, payload, invocations = 0;
let lastTimeout;
Bun.spawn = (_argv, options) => {
  invocations++;
  lastTimeout = options.timeout;
  payload = JSON.parse(new TextDecoder().decode(options.stdin));
  return {stdout: new Response(typeof response === "string" ? response : JSON.stringify(response)).body, stderr: new Response("").body, exited: Promise.resolve(status)};
};
response = {hookSpecificOutput: {permissionDecision: "deny", permissionDecisionReason: "blocked"}};
assert.deepEqual(await handlers.get("tool_call")({type: "tool_call", toolName: "bash", input: {command: "rm"}}, ctx), {block: true, reason: "blocked"});
assert.equal(payload.tool_name, "bash");
assert.ok(lastTimeout > 0 && lastTimeout <= 25000);
assert.equal(payload.hook_event_name, "PreToolUse");
assert.equal(payload.session_id, "session");
response = {hookSpecificOutput: {updatedInput: {command: "safe"}, additionalContext: "context"}};
assert.deepEqual(await handlers.get("tool_call")({type: "tool_call", toolName: "read_file", input: {}}, ctx), {input: {command: "safe"}, additionalContext: "context"});
const before = invocations;
await handlers.get("tool_call")({toolName: "write", input: {}}, ctx);
assert.equal(invocations, before);
status = 2;
assert.equal((await handlers.get("tool_call")({toolName: "bash", input: {}}, ctx)).block, true);
status = 1;
assert.equal((await handlers.get("tool_call")({toolName: "bash", input: {}}, ctx)).block, true);
assert.equal((await handlers.get("input")({text: "prompt"}, ctx)).handled, true);
status = 0;
response = "Extra instructions";
assert.deepEqual(await handlers.get("input")({text: "prompt"}, ctx), {text: "prompt\n\nExtra instructions"});
response = {updated_tool_output: "redacted", additional_context: "after"};
assert.deepEqual(await handlers.get("tool_result")({toolName: "bash", content: [], isError: false}, ctx), {content: [{type: "text", text: "redacted"}], additionalContext: "after"});
const count = invocations;
await handlers.get("tool_result")({toolName: "bash", content: [], isError: true}, ctx);
assert.equal(invocations, count);
response = {decision: "block", reason: "finish work"};
assert.deepEqual(await handlers.get("session_stop")({}, ctx), {continue: true, additionalContext: "finish work"});
response = "Startup guidance";
await handlers.get("session_start")({type: "session_start"}, ctx);
assert.equal(payload.source, "startup");
ctx.sessionManager.getBranch = () => [{type: "message"}];
await handlers.get("session_start")({type: "session_start"}, ctx);
assert.equal(payload.source, "resume");
await handlers.get("session_switch")({type: "session_switch", reason: "new"}, ctx);
assert.equal(payload.source, "clear");
await handlers.get("session_compact")({type: "session_compact"}, ctx);
assert.equal(payload.source, "compact");
assert.equal((await handlers.get("before_agent_start")({reason: "prompt"}, ctx)).message.content, "Startup guidance");
assert.equal(await handlers.get("before_agent_start")({reason: "prompt"}, ctx), undefined);

ctx.mode = "print";
response = {additional_context: "Headless input"};
assert.equal((await handlers.get("before_agent_start")({reason: "prompt", prompt: "hello"}, ctx)).message.content, "Headless input");
let aborted = false;
ctx.abort = () => {aborted = true;};
response = {decision: "deny"};
const oldExitCode = process.exitCode;
const oldExitListeners = new Set(process.rawListeners("exit"));
await handlers.get("before_agent_start")({reason: "prompt", prompt: "blocked"}, ctx);
assert.equal(aborted, true);
assert.equal(process.exitCode, 2);
for (const listener of process.rawListeners("exit")) { if (!oldExitListeners.has(listener)) process.removeListener("exit", listener); }
process.exitCode = oldExitCode ?? 0;
